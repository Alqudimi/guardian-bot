"""
Moderation Reports & Statistics
=================================
Generates moderation activity reports for group admins.

Report types:
  • On-demand — generated by /report for the requesting group
  • Reusable period report — generated for a configurable number of days

Delivery:
  • Sent to the mod-log channel if configured (/setmodlog)
  • Or directly to the requesting admin
  • Daily/weekly automatic delivery is not claimed here; Celery beat currently
    runs trust-score maintenance only.

Metrics reported:
  - Recorded moderation actions (delete / mute / ban / warn) with counts
  - Top violation categories (spam / toxic / nsfw / phishing / evasion)
  - Top 5 users attributed to recorded moderation actions
  - Newly activated raid lockdowns
  - Circuit-breaker suppressions observed for the group
  - CAPTCHA pass/fail counts
  - False positives recorded through /falsepositive
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta

from config.settings import get_settings
from src.utils.logger import get_logger
from src.utils.redis_client import get_redis

logger = get_logger(__name__)


@dataclass
class ModerationReport:
    chat_id: int
    period_start: datetime
    period_end: datetime
    total_processed: int = 0
    actions: dict[str, int] = field(default_factory=dict)
    violations: dict[str, int] = field(default_factory=dict)
    raids: int = 0
    captcha_pass: int = 0
    captcha_fail: int = 0
    top_offenders: list[tuple[int, int]] = field(default_factory=list)
    circuit_trips: int = 0
    false_positives: int = 0
    layer_failures: dict[str, int] = field(default_factory=dict)


async def record_action_stat(
    chat_id: int,
    action: str,
    violation: str,
    user_id: int | None = None,
) -> None:
    """Record a moderation action and optionally attribute it to a user."""
    redis = await get_redis()
    settings = get_settings()
    prefix = settings.redis_prefix
    today = datetime.now(tz=UTC).strftime("%Y%m%d")

    action_key = f"{prefix}stats:{chat_id}:{today}:actions"
    viol_key = f"{prefix}stats:{chat_id}:{today}:violations"
    await redis.hincrby(action_key, action, 1)
    await redis.hincrby(viol_key, violation, 1)
    await redis.expire(action_key, 86400 * 35)
    await redis.expire(viol_key, 86400 * 35)

    if user_id is not None:
        offender_key = f"{prefix}stats:{chat_id}:{today}:offenders"
        await redis.zincrby(offender_key, 1, str(user_id))
        await redis.expire(offender_key, 86400 * 35)


