async def generate_report(chat_id: int, days: int = 7) -> ModerationReport:
    """Generate a moderation report for the last N days."""
    redis = await get_redis()
    settings = get_settings()
    prefix = settings.redis_prefix

    now = datetime.now(tz=UTC)
    start = now - timedelta(days=days)
    report = ModerationReport(
        chat_id=chat_id,
        period_start=start,
        period_end=now,
    )

    # Iterate over days in the window
    actions_total: dict[str, int] = {}
    violations_total: dict[str, int] = {}
    captcha_pass = 0
    captcha_fail = 0
    raids = 0
    circuit_trips = 0
    top_offenders: dict[int, int] = {}
    layer_failures_total: dict[str, int] = {}

    for day_offset in range(days):
        day = (now - timedelta(days=day_offset)).strftime("%Y%m%d")

        # Actions
        actions_raw = await redis.hgetall(f"{prefix}stats:{chat_id}:{day}:actions")
        for k, v in actions_raw.items():
            k = k.decode() if isinstance(k, bytes) else k
            v = int(v)
            actions_total[k] = actions_total.get(k, 0) + v

        # Violations
        viol_raw = await redis.hgetall(f"{prefix}stats:{chat_id}:{day}:violations")
        for k, v in viol_raw.items():
            k = k.decode() if isinstance(k, bytes) else k
            v = int(v)
            violations_total[k] = violations_total.get(k, 0) + v

        # CAPTCHA
        cap_raw = await redis.hgetall(f"{prefix}stats:{chat_id}:{day}:captcha")
        captcha_pass += int(cap_raw.get("pass", b"0"))
        captcha_fail += int(cap_raw.get("fail", b"0"))

        # Raid and circuit events
        events_raw = await redis.hgetall(f"{prefix}stats:{chat_id}:{day}:events")
        raids += int(events_raw.get("raids", b"0"))
        circuit_trips += int(events_raw.get("circuit_trips", b"0"))

        # Layer failures are accumulated across the requested period.
        failures_raw = await redis.hgetall(
            f"{prefix}stats:{chat_id}:{day}:layer_failures"
        )
        for layer_name, value in failures_raw.items():
            layer_name = layer_name.decode() if isinstance(layer_name, bytes) else layer_name
            layer_failures_total[layer_name] = layer_failures_total.get(layer_name, 0) + int(value)

        # Offenders are accumulated across the requested period.
        offenders_raw = await redis.zrange(
            f"{prefix}stats:{chat_id}:{day}:offenders", 0, -1, withscores=True
        )
        for raw_user_id, score in offenders_raw:
            decoded_user_id = raw_user_id.decode() if isinstance(raw_user_id, bytes) else raw_user_id
            try:
                user_id = int(decoded_user_id)
            except (TypeError, ValueError):
                continue
            top_offenders[user_id] = top_offenders.get(user_id, 0) + int(score)

    report.actions = actions_total
    report.violations = violations_total
    report.total_processed = sum(actions_total.values())
    report.captcha_pass = captcha_pass
    report.captcha_fail = captcha_fail
    report.raids = raids
    report.circuit_trips = circuit_trips
    report.top_offenders = sorted(
        top_offenders.items(), key=lambda item: item[1], reverse=True
    )[:5]
    report.layer_failures = dict(
        sorted(layer_failures_total.items(), key=lambda item: item[1], reverse=True)
    )

    # False positives
    fp_val = await redis.get(f"{prefix}false_positives:{chat_id}")
    report.false_positives = int(fp_val or 0)

    return report


def format_report(report: ModerationReport, days: int = 7) -> str:
    """Format a ModerationReport as a Markdown message."""
    period = f"{report.period_start.strftime('%Y-%m-%d')} → {report.period_end.strftime('%Y-%m-%d')}"

    lines = [
        "📊 *تقرير الإشراف | Moderation Report*",
        f"🗓 الفترة | Period: `{period}`",
        f"📝 الإجراءات الكلية | Total Actions: *{report.total_processed}*\n",
    ]

    if report.actions:
        lines.append("*🔨 الإجراءات | Actions:*")
        for action, count in sorted(report.actions.items(), key=lambda x: -x[1]):
            lines.append(f"  `{action:<15}` {count}")
        lines.append("")

    if report.violations:
        lines.append("*⚠️ المخالفات | Violations:*")
        for viol, count in sorted(report.violations.items(), key=lambda x: -x[1]):
            lines.append(f"  `{viol:<15}` {count}")
        lines.append("")

    if report.captcha_pass + report.captcha_fail > 0:
        total_captcha = report.captcha_pass + report.captcha_fail
        pass_rate = report.captcha_pass / total_captcha * 100
        lines.append(
            f"*🔐 CAPTCHA:* {report.captcha_pass}✅ / {report.captcha_fail}❌ "
            f"({pass_rate:.0f}% pass)"
        )

    if report.raids > 0:
        lines.append(f"*🚨 Raids:* {report.raids}")

    if report.circuit_trips > 0:
        lines.append(f"*🛑 Circuit suppressions:* {report.circuit_trips}")

    if report.top_offenders:
        lines.append("*👤 Top offenders:*")
        lines.extend(f"  `{user_id}` — {count}" for user_id, count in report.top_offenders)

    if report.layer_failures:
        lines.append("*⚠️ Pipeline layer failures:*")
        lines.extend(
            f"  `{layer_name}` — {count}"
            for layer_name, count in report.layer_failures.items()
        )

    if report.false_positives > 0:
        lines.append(f"*📌 False Positives:* {report.false_positives}")

    return "\n".join(lines)
